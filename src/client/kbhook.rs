//! Windows: low-level keyboard hook so system keys (Win, Alt+Tab, Alt+F4, Ctrl+Esc, ...)
//! go to the remote PC instead of the Surface while streaming with input captured.

#[cfg(windows)]
pub use imp::*;

#[cfg(windows)]
mod imp {
    use std::sync::{Arc, Mutex};

    use windows_sys::Win32::Foundation::{LPARAM, LRESULT, WPARAM};
    use windows_sys::Win32::UI::Input::KeyboardAndMouse::{VK_NUMLOCK, VK_PAUSE};
    use windows_sys::Win32::UI::WindowsAndMessaging::*;

    use crate::client::input::{Hotkey, InputSender, KeyFilter};
    use crate::keymap::win_scancode_to_hid;
    use crate::protocol::InputEvent;

    struct HookState {
        sender: Arc<InputSender>,
        filter: KeyFilter,
        hwnd: isize,
        active: bool,
        on_hotkey: Box<dyn Fn(Hotkey) + Send>,
        hook: usize,
    }

    static STATE: Mutex<Option<HookState>> = Mutex::new(None);

    /// Uninstalls the hook when dropped.
    pub struct KeyboardHook(());

    pub fn install(
        sender: Arc<InputSender>,
        hwnd: isize,
        on_hotkey: Box<dyn Fn(Hotkey) + Send>,
    ) -> Option<KeyboardHook> {
        // SAFETY: standard WH_KEYBOARD_LL installation; must run on a thread with a message loop
        // (the UI thread).
        let hook = unsafe {
            let module = windows_sys::Win32::System::LibraryLoader::GetModuleHandleW(std::ptr::null());
            SetWindowsHookExW(WH_KEYBOARD_LL, Some(hook_proc), module, 0)
        };
        if hook.is_null() {
            log::warn!("Could not install keyboard hook; system keys stay local");
            return None;
        }
        *STATE.lock().unwrap() = Some(HookState {
            sender,
            filter: KeyFilter::default(),
            hwnd,
            active: false,
            on_hotkey,
            hook: hook as usize,
        });
        Some(KeyboardHook(()))
    }

    pub fn set_active(active: bool) {
        if let Ok(mut g) = STATE.lock() {
            if let Some(st) = g.as_mut() {
                if st.active != active {
                    st.filter.reset();
                }
                st.active = active;
            }
        }
    }

    impl Drop for KeyboardHook {
        fn drop(&mut self) {
            if let Some(st) = STATE.lock().unwrap().take() {
                // SAFETY: hook handle came from SetWindowsHookExW.
                unsafe {
                    UnhookWindowsHookEx(st.hook as HHOOK);
                }
            }
        }
    }

    /// Returns true if the key was consumed (sent to the host or used as a hotkey).
    fn handle(kb: &KBDLLHOOKSTRUCT, wparam: WPARAM) -> bool {
        let Ok(mut guard) = STATE.try_lock() else { return false };
        let Some(st) = guard.as_mut() else { return false };
        if !st.active || kb.flags & LLKHF_INJECTED != 0 {
            return false;
        }
        // SAFETY: trivial Win32 call.
        if unsafe { GetForegroundWindow() } as isize != st.hwnd {
            return false;
        }
        if kb.scanCode == 0x21D {
            return true; // phantom Ctrl generated by AltGr; the host gets the real AltGr
        }
        let down = matches!(wparam as u32, WM_KEYDOWN | WM_SYSKEYDOWN);
        let extended = kb.flags & LLKHF_EXTENDED != 0;
        let hid = match kb.vkCode as u16 {
            VK_PAUSE => Some(0x48),
            VK_NUMLOCK => Some(0x53),
            _ => win_scancode_to_hid(kb.scanCode as u16, extended),
        };
        let Some(hid) = hid else { return false };
        if let Some(hk) = st.filter.on_key(hid, down) {
            (st.on_hotkey)(hk);
            return true;
        }
        st.sender.send(InputEvent::Key { hid, down });
        true
    }

    unsafe extern "system" fn hook_proc(code: i32, wparam: WPARAM, lparam: LPARAM) -> LRESULT {
        if code == HC_ACTION as i32 {
            // SAFETY: for WH_KEYBOARD_LL with HC_ACTION, lparam points to a KBDLLHOOKSTRUCT.
            let kb = unsafe { &*(lparam as *const KBDLLHOOKSTRUCT) };
            if handle(kb, wparam) {
                return 1;
            }
        }
        // SAFETY: forwarding to the next hook as documented.
        unsafe { CallNextHookEx(std::ptr::null_mut(), code, wparam, lparam) }
    }
}
